-- بوابة الطلاب: الطلبات والبلاغات الخاصة
-- نفّذ هذا الملف مرة واحدة في Supabase SQL Editor.

create table if not exists public.student_portal_requests (
    id bigint generated by default as identity primary key,
    request_type text not null check (request_type in ('support', 'issue')),
    requester_name text,
    contact text,
    location text,
    details text not null,
    status text not null default 'pending'
        check (status in ('pending', 'accepted', 'rejected', 'completed')),
    created_at timestamptz not null default now()
);

alter table public.student_portal_requests enable row level security;

-- إزالة سياسات سابقة بالاسم نفسه عند إعادة تشغيل الملف
drop policy if exists "students_submit_portal_requests" on public.student_portal_requests;
drop policy if exists "staff_read_portal_requests" on public.student_portal_requests;
drop policy if exists "staff_update_portal_requests" on public.student_portal_requests;

-- يمكن للزائر/الطالب إرسال طلب جديد فقط، دون قراءة أو تعديل أي طلب.
create policy "students_submit_portal_requests"
on public.student_portal_requests
for insert
to anon, authenticated
with check (
    request_type in ('support', 'issue')
    and length(trim(details)) > 0
);

-- المدير والأمين المالي فقط يمكنهما قراءة البيانات الخاصة.
create policy "staff_read_portal_requests"
on public.student_portal_requests
for select
to authenticated
using (
    exists (
        select 1 from public.profiles p
        where p.id = auth.uid()
          and p.role in ('admin', 'treasurer')
    )
);

-- المدير والأمين المالي فقط يمكنهما تحديث حالة الطلب.
create policy "staff_update_portal_requests"
on public.student_portal_requests
for update
to authenticated
using (
    exists (
        select 1 from public.profiles p
        where p.id = auth.uid()
          and p.role in ('admin', 'treasurer')
    )
)
with check (
    exists (
        select 1 from public.profiles p
        where p.id = auth.uid()
          and p.role in ('admin', 'treasurer')
    )
);

grant insert on public.student_portal_requests to anon, authenticated;
grant select, update on public.student_portal_requests to authenticated;
grant usage, select on sequence public.student_portal_requests_id_seq to anon, authenticated;

create index if not exists student_portal_requests_created_at_idx
on public.student_portal_requests (created_at desc);
